from typing import List, Optional
from pydantic import BaseModel, Field


class NaturalLanguageTaskInput(BaseModel):
    query: str = Field(..., description="Natural language schedule command, e.g. 'gym tomorrow 6 to 7pm and study 8 to 10'")
    timezone_str: Optional[str] = Field("UTC", description="User's local timezone (e.g. 'America/New_York' or 'Europe/London')")


class CandidateTask(BaseModel):
    title: str = Field(..., description="Short descriptive title of the task")
    planned_start_time: str = Field(..., description="Planned start time in ISO 8601 format (UTC)")
    planned_end_time: str = Field(..., description="Planned end time in ISO 8601 format (UTC)")


class NaturalLanguageTaskResponse(BaseModel):
    candidate_tasks: List[CandidateTask] = Field(default_factory=list, description="List of proposed tasks extracted via function calling")
    explanation: str = Field(..., description="Explanation of parsed dates and function calling execution")


class BatchCreateTasksInput(BaseModel):
    tasks: List[CandidateTask] = Field(..., description="Confirmed candidate tasks to save to the database")


class JournalInsightsSchema(BaseModel):
    """
    Pydantic schema enforcing structured JSON output from Gemini for daily journal entries.
    """
    mood: str = Field(..., description="Dominant emotional state or mindset detected in the journal entry")
    key_activities: List[str] = Field(default_factory=list, description="List of notable events or activities mentioned")
    wins: List[str] = Field(default_factory=list, description="Achievements, positive moments, or gratitude items")
    problems: List[str] = Field(default_factory=list, description="Obstacles, frustrations, or blockers encountered")
    suggestion_for_tomorrow: str = Field(..., description="One actionable, constructive recommendation for tomorrow")


class AICoachReviewResponse(BaseModel):
    """
    Structured performance evaluation generated by the AI Coach.
    """
    strengths: List[str] = Field(..., description="Areas where discipline and performance were strongest")
    weaknesses: List[str] = Field(..., description="Patterns of slippage, overdue tasks, or poor estimation")
    action_items: List[str] = Field(..., min_length=3, max_length=3, description="Exactly 3 concrete actions for next week")
    motivational_summary: str = Field(..., description="Encouraging but candid summary of progress")
    includes_journal_text: bool = Field(False, description="Whether private journal entries were included in this analysis")


class AskJournalRequest(BaseModel):
    query: str = Field(..., description="Question to ask across your past journal entries")


class AskJournalResponse(BaseModel):
    query: str = Field(..., description="Original user question")
    answer: str = Field(..., description="Answer synthesized strictly from past journal entries")
    source_dates: List[str] = Field(default_factory=list, description="List of calendar dates (YYYY-MM-DD) cited as sources")
    used_fallback: bool = Field(False, description="True if no relevant past entries were found or AI fallback was used")
